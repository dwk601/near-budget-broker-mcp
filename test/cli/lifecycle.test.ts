import { describe, expect, it } from 'vitest';
import { readFile, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import type { Transport } from '@modelcontextprotocol/sdk/shared/transport.js';
import { startDaemon } from '../../src/daemon/index.js';
import { adminOperations } from '../../src/daemon/admin.js';
import { runCli } from '../../src/cli/index.js';
import { OwnerClient } from '../../src/cli/client.js';
import { signOwnerRequest } from '../../src/auth/index.js';
import { json } from '../../src/daemon/wire.js';
import { fixture } from './helpers.js';

const passphrase = 'test only long passphrase';
describe('daemon and owner CLI', () => {
  it('owner CLI end-to-end; signed-only admin, persistent freeze/replay, checkpoints and offline verification', async () => {
    const f = await fixture(); let daemon: Awaited<ReturnType<typeof startDaemon>> | undefined;
    const mcp = new Client({ name: 'cli-test', version: '1' });
    const keyPath = join(f.dir, 'owner.json'); const tokenPath = join(f.dir, 'token');
    const env = { BB_OWNER_PASSPHRASE: passphrase, BB_OWNER_KEY_FILE: keyPath, BB_ADMIN_URL: `http://127.0.0.1:${f.config.adminPort}` };
    let stdout = ''; let stderr = '';
    async function cli(...args: string[]) {
      stdout = ''; stderr = '';
      const code = await runCli(['owner', ...args, '--json'], { env, stdout: (s) => { stdout += s; }, stderr: (s) => { stderr += s; } });
      expect(code, stderr).toBe(0); return JSON.parse(stdout) as Record<string, any>;
    }
    try {
      const initialized = await cli('init-owner-key', '--out', keyPath);
      f.config.ownerPublicKey = initialized['publicKey'] as string;
      // Independent owner client below uses the actual decrypted key generated by CLI.
      const { unlockOwnerKey } = await import('../../src/cli/keys.js');
      const ownerKey = await unlockOwnerKey(keyPath, passphrase);
      const owner = new OwnerClient(env.BB_ADMIN_URL, ownerKey);
      daemon = await startDaemon({ config: f.config, dependencies: f.dependencies, intervalMs: 60_000, log: () => {} });
      const agent = await cli('agent', 'create', 'hostile-agent'); const agentId = agent['id'] as string;
      expect((await cli('agent', 'list'))['items']).toHaveLength(1);
      const written = await cli('token', 'issue', agentId, '--out', tokenPath);
      expect(written).toEqual({ path: tokenPath }); expect(stdout).not.toContain('bb_agent_');
      const token = (await readFile(tokenPath, 'utf8')).trim();
      expect((await stat(tokenPath)).mode & 0o777).toBe(0o600);
      const policyPath = join(f.dir, 'policy.json');
      await writeFile(policyPath, json({ agentId, revision: 1, perTxMax: '0.1', rolling24hMax: '1', lifetimeMax: '1', gasBudget24h: '1',
        ratePerMinute: 100, maxOutstanding: 10, recipients: { mode: 'allow_all', accounts: [] }, approvalThreshold: '0' }));
      const policy = await cli('policy', 'set', '--file', policyPath);
      expect(policy['perTxMax']).toBe('100000000000000000000000');
      expect((await cli('policy', 'get', agentId))['revision']).toBe(1);
      const walletPath = join(f.dir, 'wallet.json');
      await writeFile(walletPath, json({ revision: 1, rolling24hMax: '1', safetyReserve: '0' }));
      await cli('wallet-policy', 'set', '--file', walletPath);
      await cli('freeze', 'agent', agentId, 'review'); await cli('unfreeze', 'agent', agentId, 'reviewed');
      const transport = new StreamableHTTPClientTransport(new URL(`http://127.0.0.1:${f.config.agentPort}/mcp`), { requestInit: { headers: { Authorization: `Bearer ${token}` } } });
      await mcp.connect(transport as Transport);
      const response = await mcp.callTool({ name: 'request_transfer', arguments: { idempotencyKey: 'first', receiverId: 'receiver.testnet', amount: '1' } });
      expect(response.isError).not.toBe(true);
      const requests = await cli('requests', 'list'); const request = requests['items'][0] as { id: string; state: string };
      expect(request.state).toBe('pending_approval');
      expect((await cli('approvals', 'list'))['items']).toHaveLength(1);
      expect((await cli('approvals', 'approve', request.id, String(Date.now() + 60_000)))['state']).toBe('queued');
      const grantPath = join(f.dir, 'grant.json');
      await writeFile(grantPath, json({ agentId, perTxMax: '0.1', totalMax: '0.2', expiresAt: Date.now() + 60_000 }));
      const grant = await cli('standing', 'grant', '--file', grantPath);
      expect((await cli('standing', 'list', agentId))['items']).toHaveLength(1);
      await cli('standing', 'revoke', grant['id'] as string);
      expect((await cli('requests', 'get', request.id))['id']).toBe(request.id);
      await cli('reconcile', request.id);
      const secondResponse = await mcp.callTool({ name: 'request_transfer', arguments: { idempotencyKey: 'second', receiverId: 'receiver.testnet', amount: '1' } });
      expect(secondResponse.isError).not.toBe(true);
      const pendingSecond = ((await cli('approvals', 'list'))['items'] as { id: string }[])[0]!;
      expect((await cli('approvals', 'reject', pendingSecond.id, 'not needed'))['state']).toBe('rejected');
      // Verify every admin operation rejects even a VALID active agent bearer.
      const before = await owner.call('exportReceipts', { chainId: 'owner', afterSeq: 0, limit: 1000 });
      for (const op of [...adminOperations, 'nonexistent']) {
        const denied = await fetch(`${env.BB_ADMIN_URL}/admin/${op}`, { method: 'POST', headers: { Authorization: `Bearer ${token}` }, body: '{}' });
        expect([401, 403]).toContain(denied.status);
      }
      expect(await owner.call('exportReceipts', { chainId: 'owner', afterSeq: 0, limit: 1000 })).toEqual(before);
      const credentialEvents = await owner.call('exportReceipts', { chainId: `agent:${agentId}`, afterSeq: 0, limit: 1000 }) as { type: string; payload: { credentialId: string } }[];
      const credentialId = credentialEvents.find((e) => e.type === 'credential_issued')!.payload.credentialId;
      // An existing output file is refused BEFORE rotation revokes a live token.
      expect(await runCli(['owner', 'token', 'rotate', credentialId, '--out', tokenPath], { env, stdout: () => {}, stderr: () => {} })).toBe(1);
      const rotatedPath = join(f.dir, 'rotated-token'); await cli('token', 'rotate', credentialId, '--out', rotatedPath);
      expect((await stat(rotatedPath)).mode & 0o777).toBe(0o600);
      const agentStatus = (bearer: string) => fetch(`http://127.0.0.1:${f.config.agentPort}/mcp`, { headers: { Authorization: `Bearer ${bearer}` } });
      expect((await agentStatus(token)).status).toBe(401);
      const rotatedToken = (await readFile(rotatedPath, 'utf8')).trim();
      expect((await agentStatus(rotatedToken)).status).not.toBe(401);
      const rotatedEvents = await owner.call('exportReceipts', { chainId: `agent:${agentId}`, afterSeq: 0, limit: 1000 }) as { type: string; payload: { credentialId: string } }[];
      const rotatedId = rotatedEvents.filter((e) => e.type === 'credential_issued').at(-1)!.payload.credentialId;
      await cli('token', 'revoke', rotatedId); expect((await agentStatus(rotatedToken)).status).toBe(401);
      expect((await cli('agent', 'revoke', agentId, 'retired'))['status']).toBe('revoked');
      // Same signed request can mutate exactly once, including after a restart.
      const body = json({ target: { scope: 'global' }, reason: 'persisted' }); const path = '/admin/freeze';
      const headers = signOwnerRequest(ownerKey, 'POST', path, body);
      const replay = () => fetch(`${env.BB_ADMIN_URL}${path}`, { method: 'POST', headers, body });
      expect((await replay()).status).toBe(200); expect((await replay()).status).toBe(401);
      await expect(startDaemon({ config: f.config, dependencies: f.dependencies, log: () => {} })).rejects.toThrow('Exclusive custody lock');
      await mcp.close(); await daemon.close(); daemon = undefined;
      daemon = await startDaemon({ config: f.config, dependencies: f.dependencies, intervalMs: 60_000, log: () => {} });
      expect((await replay()).status).toBe(401);
      expect(await owner.call('getFreeze', { target: { scope: 'global' } })).toMatchObject({ frozen: true, reason: 'persisted' });
      const exportPath = join(f.dir, 'receipts.json'); await cli('receipts', 'export', 'owner', '--out', exportPath);
      const checkpoints = await cli('checkpoints', 'list', 'owner') as unknown as { seq: number }[];
      expect(checkpoints.length).toBeGreaterThan(0);
      const checkpointPath = join(f.dir, 'pin.json'); await writeFile(checkpointPath, json(checkpoints.at(-1)));
      const auditKey = await owner.call('auditPublicKey') as string;
      // Offline verify succeeds with no running daemon and detects truncation.
      await daemon.close(); daemon = undefined;
      expect((await cli('receipts', 'verify', '--file', exportPath, '--checkpoint', checkpointPath, '--audit-key', auditKey))['valid']).toBe(true);
      const events = JSON.parse(await readFile(exportPath, 'utf8')) as unknown[];
      await writeFile(exportPath, json(events.slice(0, -1)));
      expect(await runCli(['owner', 'receipts', 'verify', '--file', exportPath, '--checkpoint', checkpointPath, '--audit-key', auditKey], { stdout: () => {}, stderr: () => {} })).toBe(1);
      expect(stderr).not.toContain(token);
    } finally { await mcp.close(); await daemon?.close(); await f.cleanup(); }
  }, 60_000);

  it('refuses non-testnet before unlocking/serving and releases startup locks', async () => {
    const f = await fixture();
    try {
      f.chain.network = 'mainnet';
      await expect(startDaemon({ config: f.config, dependencies: f.dependencies, log: () => {} })).rejects.toThrow();
      f.chain.network = 'testnet';
      const daemon = await startDaemon({ config: f.config, dependencies: f.dependencies, log: () => {} }); await daemon.close();
    } finally { await f.cleanup(); }
  });
});
